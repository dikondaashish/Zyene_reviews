/**
 * File size guard — enforces the limits in AGENTS.md §2.
 *
 * AGENTS.md has called these limits "non-negotiable" since the repo started, but
 * nothing enforced them, so 39 files drifted over. Splitting them all at once
 * would be churn for its own sake; several are cohesive static datasets where a
 * split buys nothing.
 *
 * So this is a ratchet, not a cliff:
 *   - A file not in BASELINE must be under its category limit.
 *   - A file in BASELINE must not grow beyond its recorded size.
 *   - A file in BASELINE that drops under its limit must be removed from
 *     BASELINE (the guard tells you, so the list can only shrink).
 *
 * Net effect: existing debt is frozen and pays down over time, and no new
 * oversized file can land.
 */
import fs from "node:fs";
